// 특정 월령(소수 가능)에서 percentile 값을 선형 보간으로 계산. 범위를 벗어나면 양 끝값으로 고정(clamp).
export function whoValueAt(measure, gender, percentile, ageMonths) {
  const table = WHO_DATA[measure]?.[gender]?.[percentile];
  if (!table) return null;
  const ages = WHO_AGE_MONTHS;
  if (ageMonths <= ages[0]) return table[0];
  if (ageMonths >= ages[ages.length - 1]) return table[table.length - 1];
  for (let i = 0; i < ages.length - 1; i++) {
    if (ageMonths >= ages[i] && ageMonths <= ages[i + 1]) {
      const t = (ageMonths - ages[i]) / (ages[i + 1] - ages[i]);
      return table[i] + (table[i + 1] - table[i]) * t;
    }
  }
  return null;
}

// 생년월일(YYYY-MM-DD, 한국 날짜 기준)과 측정 시각(ISO)으로부터 만 개월 수(소수)를 계산.
export function ageMonthsAt(birthDate, isoTime) {
  if (!birthDate) return null;
  const [by, bm, bd] = birthDate.split('-').map(Number);
  const birthMs = Date.UTC(by, bm - 1, bd);
  const t = new Date(isoTime).getTime();
  const days = (t - birthMs) / 86400000;
  return days / 30.4375; // 평균 한 달 길이로 환산
}
